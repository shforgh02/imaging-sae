"""Stage 1a read-out (docs/STAGE1A_PROTOCOL.md section 5): sanity rows, rep-0 candidates per family, representatives on reps 0-2,
gate G1 (G1-cal, G1-main) exactly as fixed, and the descriptive tests T4-T9. Writes RESULTS_S1A.md and results/s1a_g1.json.
usage (from v2_ct/): ..\\..\\.venv\\Scripts\\python s1a_summary.py
"""
import json

import numpy as np

from s1a_lib import HERE, RES, SAN, methods

P = "area_matched_neutral"; BASE_FAMS = ("kmeans", "ica", "dl", "raw", "svx")


def load(name):
    p = RES / name; return json.load(open(p)) if p.exists() else {}


def f3(x): return "–" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.3f}"


def main():
    cpu, gpu, refs, sel = load("s1a_cpu.json"), load("s1a_sae.json"), load("s1a_refs.json"), load("s1a_selection.json")
    a3s = json.load(open(SAN / "results" / "a3_sae.json")); a2 = json.load(open(SAN / "results" / "a2_sae_audit.json")); M = methods()
    allr = {**cpu, **gpu}; rep_of = sel.get("representative", {}); sae_rep = rep_of.get("sae", "cons_M1024_k6_s12000"); out = dict(representatives=rep_of)
    md = ["# Stage 1a results (exploratory, 150 development scans)", "",
          "Protocol `docs/STAGE1A_PROTOCOL.md` (fixed before running). Primary metric: area under C(τ) at 425 features, 'neutral' rule. Generated by `s1a_summary.py`.", ""]
    # ---- sanity
    md += ["## Sanity rows", "", "| Row | Check | Max abs diff |", "|---|---|---|"]
    for k, r in sorted(cpu.items()):
        if "sanity_vs_a3" in r: md.append(f"| {k} | = a3_cpu.json (R1, 4 areas) | {max(r['sanity_vs_a3'].values()):.1e} |")
    for rep in (0, 1, 2):
        k = f"sae_M1024_k6_s12000_rep{rep}"; ref = a3s.get(f"sae_best_k6_rep{rep}")
        if k in gpu and ref: md.append(f"| {k} | vs a3_sae.json (L4) | {max(abs(gpu[k][x] - ref[x]) for x in ('R1', 'area_orig', 'area_neutral', P)):.1e} |")
    k = "cons_M1024_k6_s12000_rep0"
    if k in gpu: md.append(f"| {k} | vs A2 consensus (local GPU) | {max(abs(gpu[k][x] - a2['cons_M1024_k6_s12000'][x]) for x in ('R1', 'area_orig', 'area_neutral', P)):.1e} |")
    # ---- rep-0 candidates
    md += ["", "## Rep-0 candidates per family (selection rule: max primary, ties → R1)", "",
           "| Family | Candidate | Features | L0 | R1 | Primary (425, neutral) | Area neutral (all) | 425, orig | C(0.7) neutral A/B | Precision (v ≥ 0.7) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for fam, cands in sel.get("candidates", {}).items():
        for n, v, _ in sorted(cands, key=lambda t: -t[1]):
            r = cpu.get(f"{n}_rep0") if fam != "sae" else None; star = " **(rep)**" if n == rep_of.get(fam) else ""
            if r: md.append(f"| {fam} | {n}{star} | {r['n_feat']['A']} | {np.mean(list(r['L0'].values())):.1f} | {r['R1']:.2f} | {f3(r[P])} | {f3(r['area_neutral'])} | {f3(r['area_matched_orig'])} | {r['C07_neutral']} | {f3(r['feat']['neutral']['precision07'])} |")
            else: md.append(f"| {fam} | {n}{star} (A2) | | | {_:.2f} | {f3(v)} | | | | |")
    # ---- representatives on reps 0-2 and G1
    fams = [f for f in BASE_FAMS if f in rep_of]; rows = {f: [allr.get(f"{rep_of[f]}_rep{r}") for r in (0, 1, 2)] for f in fams}
    sae_rows = [gpu.get(f"{sae_rep}_rep{r}") for r in (0, 1, 2)]; ora = [cpu.get(f"oracle_rep{r}") for r in (0, 1, 2)]
    md += ["", "## Representatives, reps 0–2 (primary metric)", "", "| Method | Rep 0 | Rep 1 | Rep 2 | Mean | R1 (mean) |", "|---|---|---|---|---|---|"]
    def line(lbl, rr): v = [x[P] if x else None for x in rr]; ok = [x for x in v if x is not None]; return f"| {lbl} | " + " | ".join(f3(x) for x in v) + f" | {f3(np.mean(ok) if ok else None)} | {f3(np.mean([x['R1'] for x in rr if x]) if any(rr) else None)} |"
    md.append(line(f"SAE representative ({sae_rep})", sae_rows))
    for f in fams: md.append(line(f"{f}: {rep_of[f]}", rows[f]))
    for n in ("sae_M1024_k6_s12000", "nullsae_M1024_k6_s12000", "physsae_M1024_k6_s12000"): md.append(line(f"(descriptive) {n}", [gpu.get(f"{n}_rep{r}") for r in (0, 1, 2)]))
    md.append(line("(reference) oracle", ora))
    complete = all(sae_rows) and all(all(v) for v in rows.values()) and all(ora)
    g1 = dict(complete=complete)
    if complete:
        gains, strongest = [], []
        for r in range(3):
            b = {f: rows[f][r][P] for f in fams}; fb = max(b, key=b.get); gains.append(sae_rows[r][P] - b[fb]); strongest.append(fb)
        main_pass = all(g > 0 for g in gains) and float(np.mean(gains)) >= .05
        c07 = [c for x in ora for c in x["C07_neutral"]]; cal = float(np.mean(c07)); cal_pass = cal >= 20
        branch = "pass" if main_pass else ("sparse-coding branch" if strongest.count("dl") >= 2 else "stop branch")
        g1.update(gains=gains, mean_gain=float(np.mean(gains)), strongest_baseline=strongest, G1_main=main_pass, oracle_C07_halves=c07, oracle_C07_mean=cal,
                  G1_cal=cal_pass, branch=branch, pct_of_oracle=[sae_rows[r][P] / ora[r][P] for r in range(3)])
        md += ["", "## Gate G1 (as fixed)", "",
               f"- **G1-cal** (oracle C(0.7) 'neutral', mean of 6 half-models ≥ 20 of 32): {cal:.1f} (halves {c07}) → **{'PASS' if cal_pass else 'FAIL'}**",
               f"- **G1-main** (SAE representative − best baseline representative, each rep > 0 and mean ≥ 0.05): gains {', '.join(f'{g:+.3f}' for g in gains)}; mean {np.mean(gains):+.3f}; strongest baseline per rep {strongest} → **{'PASS' if main_pass else 'FAIL'}** ({branch})",
               f"- SAE as share of the oracle (descriptive): {', '.join(f'{x:.2f}' for x in g1['pct_of_oracle'])}"]
    else: md += ["", "## Gate G1", "", "Not read yet: some representative rows are missing."]
    out["G1"] = g1
    # ---- descriptive
    desc = [("SAE consensus", sae_rep), ("SAE single", "sae_M1024_k6_s12000")] + [(f, rep_of[f]) for f in fams] + [("oracle", "oracle"), ("null SAE (untrained)", "nullsae_M1024_k6_s12000"), ("physics SAE (R3)", "physsae_M1024_k6_s12000")]
    md += ["", "## Descriptive (mean over available reps)", "", "### T4 precision, T8 shortcut, T5 θ", "",
           "| Method | Features | V0 | Share of V0 on 'other' | Precision neutral | Precision orig | Valid (v ≥ 0.7) neutral | Shortcut share | θ neutral (n+/n−) | θ orig (n+/n−) |", "|---|---|---|---|---|---|---|---|---|---|"]
    def mean_of(name, fn):
        v = [fn(allr[f"{name}_rep{r}"]) for r in (0, 1, 2) if f"{name}_rep{r}" in allr]; v = [x for x in v if x is not None and np.isfinite(x)]; return float(np.mean(v)) if v else None
    def th(name, rule):
        rr = [allr[f"{name}_rep{r}"]["feat"][rule]["theta"] for r in (0, 1, 2) if f"{name}_rep{r}" in allr]
        return "–" if not rr else f"{np.nanmean([x['theta'] for x in rr]):.2f} ({int(np.mean([x['n_pos'] for x in rr]))}/{int(np.mean([x['n_neg'] for x in rr]))})"
    for lbl, n in desc:
        if f"{n}_rep0" not in allr and f"{n}_rep1" not in allr: continue
        g = lambda k1, k2=None: mean_of(n, lambda x: x["feat"][k1] if k2 is None else x["feat"][k1][k2])  # noqa: E731
        md.append(f"| {lbl} | {f3(g('n_feat'))[:-4]} | {f3(g('n_v0'))[:-4]} | {f3(g('share_other_v0'))} | {f3(g('neutral', 'precision07'))} | {f3(g('orig', 'precision07'))} | {f3(g('neutral', 'n_valid07'))[:-4]} | {f3(mean_of(n, lambda x: x['feat']['shortcut']['share']))} | {th(n, 'neutral')} | {th(n, 'orig')} |")
    md += ["", "### T6 k = 1 sparse probing (median AUROC over classes; native / 425 candidates)", "", "| Method | Organ groups (33) | Vertebral level (24) | Lung lobe (5) |", "|---|---|---|---|"]
    for lbl, n in desc:
        if f"{n}_rep0" not in allr and f"{n}_rep1" not in allr: continue
        cells = [f"{f3(mean_of(n, lambda x, t=t: x['k1'][t]['median']))} / {f3(mean_of(n, lambda x, t=t: x['k1'][t]['median_matched']))}" for t in ("T1b", "T3_vert", "T3_lobe")]
        md.append(f"| {lbl} | " + " | ".join(cells) + " |")
    for s, lbl in (("ctfm", "dense CT-FM probe"), ("R4", "dense physics R4 probe"), ("null", "dense untrained CT-FM probe")):
        v = [refs[f"{s}_rep{r}"] for r in (0, 1, 2) if f"{s}_rep{r}" in refs]
        if v: md.append(f"| ({lbl}) | " + " | ".join(f3(np.mean([x[t]["median"] for x in v])) for t in ("T1b", "T3_vert", "T3_lobe")) + " |")
    (HERE / "RESULTS_S1A.md").write_text("\n".join(md) + "\n", encoding="utf8"); json.dump(out, open(RES / "s1a_g1.json", "w"), indent=1, default=float)
    print("\n".join(md))


if __name__ == "__main__":
    main()
